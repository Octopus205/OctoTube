enum class SponsorCategory(
    val apiKey: String,
    val labelAr: String
) {
    SPONSOR("sponsor", "إعلان مدفوع"),
    SELF_PROMO("selfpromo", "ترويج ذاتي"),
    INTRO("intro", "مقدمة"),
    OUTRO("outro", "خاتمة"),
    INTERACTION("interaction", "تذكير بالاشتراك"),
    MUSIC_OFFTOPIC("music_offtopic", "مقطع غير موسيقي");

    companion object {
        fun fromKey(key: String): SponsorCategory =
            entries.firstOrNull { it.apiKey == key } ?: SPONSOR
    }
}

