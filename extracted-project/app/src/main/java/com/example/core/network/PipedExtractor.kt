package com.example.core.network

import com.example.domain.model.AudioStreamOption
import com.example.domain.model.ChannelDetail
import com.example.domain.model.ChapterMark
import com.example.domain.model.ServiceProvider
import com.example.domain.model.StreamDetail
import com.example.domain.model.SubtitleTrack
import com.example.domain.model.VideoStreamOption
import com.example.domain.model.VideoSummary
import kotlinx.serialization.Serializable
import java.net.URLEncoder

@Serializable
private data class PipedVideoItemDto(
    val url: String = "",
    val type: String = "stream",
    val title: String = "",
    val thumbnail: String = "",
    val uploaderName: String = "",
    val uploaderUrl: String = "",
    val uploaderAvatar: String? = null,
    val uploadedDate: String? = null,
    val duration: Long = 0L,
    val views: Long = 0L,
    val isShort: Boolean = false
)

@Serializable
private data class PipedSearchResponseDto(
    val items: List<PipedVideoItemDto> = emptyList()
)

@Serializable
private data class PipedVideoStreamDto(
    val url: String = "",
    val format: String = "",
    val quality: String = "",
    val mimeType: String = "",
    val height: Int = 0,
    val bitrate: Long = 0L,
    val videoOnly: Boolean = false,
    val contentLength: Long = 0L
)

@Serializable
private data class PipedAudioStreamDto(
    val url: String = "",
    val format: String = "",
    val quality: String = "",
    val mimeType: String = "",
    val bitrate: Long = 0L,
    val contentLength: Long = 0L
)

@Serializable
private data class PipedSubtitleDto(
    val url: String = "",
    val mimeType: String = "text/vtt",
    val name: String = "",
    val code: String = "",
    val autoGenerated: Boolean = false
)

@Serializable
private data class PipedChapterDto(
    val title: String = "",
    val image: String? = null,
    val start: Long = 0L
)

@Serializable
private data class PipedStreamResponseDto(
    val title: String = "",
    val description: String = "",
    val uploadDate: String = "",
    val uploader: String = "",
    val uploaderUrl: String = "",
    val uploaderAvatar: String? = null,
    val uploaderSubscriberCount: Long = 0L,
    val thumbnailUrl: String = "",
    val hls: String? = null,
    val duration: Long = 0L,
    val views: Long = 0L,
    val likes: Long = 0L,
    val videoStreams: List<PipedVideoStreamDto> = emptyList(),
    val audioStreams: List<PipedAudioStreamDto> = emptyList(),
    val subtitles: List<PipedSubtitleDto> = emptyList(),
    val chapters: List<PipedChapterDto> = emptyList(),
    val relatedStreams: List<PipedVideoItemDto> = emptyList()
)

@Serializable
private data class PipedChannelResponseDto(
    val id: String = "",
    val name: String = "",
    val avatarUrl: String? = null,
    val bannerUrl: String? = null,
    val description: String = "",
    val subscriberCount: Long = 0L,
    val relatedStreams: List<PipedVideoItemDto> = emptyList()
)

class PipedExtractor {
    suspend fun getTrending(baseUrl: String, region: String = "SA"): List<VideoSummary> {
        val cleanBase = baseUrl.trimEnd('/')
        val body = NetworkModule.getString("$cleanBase/trending?region=$region")
        val items = NetworkModule.json.decodeFromString<List<PipedVideoItemDto>>(body)
        return items.mapNotNull { it.toVideoSummary() }
    }

    suspend fun search(baseUrl: String, query: String): List<VideoSummary> {
        val cleanBase = baseUrl.trimEnd('/')
        val encoded = URLEncoder.encode(query, "UTF-8")
        val body = NetworkModule.getString("$cleanBase/search?q=$encoded&filter=videos")
        val response = NetworkModule.json.decodeFromString<PipedSearchResponseDto>(body)
        return response.items.mapNotNull { it.toVideoSummary() }
    }

    suspend fun getStreamDetail(baseUrl: String, videoId: String): StreamDetail {
        val cleanBase = baseUrl.trimEnd('/')
        val body = NetworkModule.getString("$cleanBase/streams/$videoId")
        val dto = NetworkModule.json.decodeFromString<PipedStreamResponseDto>(body)

        val videoOptions = dto.videoStreams
            .filter { it.url.isNotBlank() }
            .map {
                VideoStreamOption(
                    url = it.url,
                    qualityLabel = it.quality.ifBlank { "${it.height}p" },
                    height = it.height,
                    mimeType = it.mimeType.ifBlank { "video/mp4" },
                    videoOnly = it.videoOnly,
                    bitrate = it.bitrate,
                    contentLength = it.contentLength
                )
            }
            .sortedWith(compareBy<VideoStreamOption> { it.videoOnly }.thenByDescending { it.height })

        val audioOptions = dto.audioStreams
            .filter { it.url.isNotBlank() }
            .map {
                AudioStreamOption(
                    url = it.url,
                    qualityLabel = it.quality.ifBlank { "${it.bitrate / 1000} kbps" },
                    bitrate = it.bitrate,
                    mimeType = it.mimeType.ifBlank { "audio/mp4" },
                    contentLength = it.contentLength
                )
            }
            .sortedByDescending { it.bitrate }

        val subtitleTracks = dto.subtitles
            .filter { it.url.isNotBlank() }
            .map {
                SubtitleTrack(
                    url = it.url,
                    languageCode = it.code.ifBlank { "en" },
                    languageName = it.name.ifBlank { it.code },
                    mimeType = it.mimeType.ifBlank { "text/vtt" },
                    isAutoGenerated = it.autoGenerated
                )
            }

        val chapters = dto.chapters.map {
            ChapterMark(title = it.title, startSeconds = it.start, thumbnailUrl = it.image)
        }

        val channelId = extractChannelId(dto.uploaderUrl)

        return StreamDetail(
            id = videoId,
            title = dto.title,
            description = dto.description,
            channelId = channelId,
            channelName = dto.uploader,
            channelAvatarUrl = dto.uploaderAvatar,
            subscriberCountText = formatSubscribers(dto.uploaderSubscriberCount),
            thumbnailUrl = dto.thumbnailUrl,
            durationSeconds = dto.duration,
            views = dto.views,
            likes = dto.likes,
            uploadDate = dto.uploadDate,
            serviceProvider = ServiceProvider.PIPED,
            hlsUrl = dto.hls,
            videoStreams = videoOptions,
            audioStreams = audioOptions,
            subtitles = subtitleTracks,
            chapters = chapters,
            relatedVideos = dto.relatedStreams.mapNotNull { it.toVideoSummary() },
            sourceInstance = cleanBase
        )
    }

    suspend fun getChannel(baseUrl: String, channelId: String): ChannelDetail {
        val cleanBase = baseUrl.trimEnd('/')
        val body = NetworkModule.getString("$cleanBase/channel/$channelId")
        val dto = NetworkModule.json.decodeFromString<PipedChannelResponseDto>(body)
        return ChannelDetail(
            id = dto.id.ifBlank { channelId },
            name = dto.name,
            avatarUrl = dto.avatarUrl,
            bannerUrl = dto.bannerUrl,
            description = dto.description,
            subscriberCount = dto.subscriberCount,
            serviceProvider = ServiceProvider.PIPED,
            videos = dto.relatedStreams.mapNotNull { it.toVideoSummary() }
        )
    }

    private fun PipedVideoItemDto.toVideoSummary(): VideoSummary? {
        val id = extractVideoId(url) ?: return null
        if (title.isBlank()) return null
        return VideoSummary(
            id = id,
            title = title,
            channelId = extractChannelId(uploaderUrl),
            channelName = uploaderName.ifBlank { "قناة" },
            channelAvatarUrl = uploaderAvatar,
            thumbnailUrl = thumbnail,
            durationSeconds = duration,
            views = views,
            uploadedText = uploadedDate.orEmpty(),
            serviceProvider = ServiceProvider.PIPED,
            isLive = duration <= 0L
        )
    }

    private fun extractVideoId(url: String): String? {
        val vIdx = url.indexOf("v=")
        if (vIdx != -1) {
            return url.substring(vIdx + 2).substringBefore("&")
        }
        return url.substringAfterLast("/").takeIf { it.isNotBlank() }
    }

    private fun extractChannelId(uploaderUrl: String): String {
        return uploaderUrl.substringAfterLast("/").ifBlank { "unknown_channel" }
    }

    private fun formatSubscribers(count: Long): String = when {
        count >= 1_000_000 -> String.format("%.1fM مشترك", count / 1_000_000.0)
        count >= 1_000 -> String.format("%.1fK مشترك", count / 1_000.0)
        count > 0 -> "$count مشترك"
        else -> ""
    }
}
